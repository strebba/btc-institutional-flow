-- Barre giornaliere: partial=1 è la sessione UTC non ancora chiusa.
-- Il close di quella riga non è un close; la verifica lo ignora.
-- DEFAULT 0: le righe già migrate restano "complete" finché un fetch o il
-- backfill non le riscrive.

ALTER TABLE prices ADD COLUMN IF NOT EXISTS partial INTEGER NOT NULL DEFAULT 0;

-- Copia degli esiti prima di scripts/rescore_outcomes.py --write.
-- Non ha FK: l'archivio sopravvive anche se non si toccano le predizioni,
-- e un rescore non deve modificare predictions.

CREATE TABLE IF NOT EXISTS outcomes_archive (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_id    BIGINT NOT NULL,
    hit              INTEGER NOT NULL,
    realized_return  DOUBLE PRECISION,
    realized_price   DOUBLE PRECISION,
    ref_price        DOUBLE PRECISION,
    signed_error     DOUBLE PRECISION,
    brier            DOUBLE PRECISION,
    detail           TEXT,
    scored_at        TEXT NOT NULL,
    archived_at      TEXT NOT NULL,
    reason           TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_outcomes_archive_pred ON outcomes_archive(prediction_id);
