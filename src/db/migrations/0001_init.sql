-- Schema Postgres iniziale: equivalente allo schema SQLite corrente.
--
-- Rispecchia le DDL di PredictionDB, AlertDB, PriceFetcher, GexDB e
-- StructuredNotesDB (user_version 4). Convenzioni, per restare compatibili
-- con il codice e con i dati migrati da SQLite:
--   * date e timestamp restano TEXT ISO (il codice li confronta come stringhe);
--   * JSON resta TEXT (il codice fa json.loads/dumps);
--   * REAL -> DOUBLE PRECISION, flag 0/1 -> INTEGER;
--   * gli id sono IDENTITY "BY DEFAULT": la migrazione da SQLite puo' inserire
--     gli id originali (riferiti da FK) e poi riallinea le sequenze.
-- Applicato da src.db.ensure_postgres_schema(), tracciato in schema_migrations.

-- ─── Forecast (PredictionDB) ────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS predictions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at       TEXT NOT NULL,
    date             TEXT NOT NULL,
    source           TEXT NOT NULL,
    asset            TEXT NOT NULL,
    target_type      TEXT NOT NULL,
    target_spec      TEXT NOT NULL,
    horizon_days     INTEGER NOT NULL,
    confidence       DOUBLE PRECISION NOT NULL,
    rationale        TEXT,
    counter_analysis TEXT,
    human_overlay    TEXT,
    score_ref        DOUBLE PRECISION,
    components       TEXT,
    weights_version  BIGINT,
    model_version    TEXT NOT NULL DEFAULT 'v1',
    status           TEXT NOT NULL DEFAULT 'open',
    UNIQUE (created_at, source, target_type, horizon_days)
);
CREATE INDEX IF NOT EXISTS idx_pred_status ON predictions(status);
CREATE INDEX IF NOT EXISTS idx_pred_date   ON predictions(date);
CREATE INDEX IF NOT EXISTS idx_pred_source ON predictions(source);
-- una predizione per giorno/source/target/orizzonte (idempotenza dei job)
CREATE UNIQUE INDEX IF NOT EXISTS idx_pred_day_unique
    ON predictions(date, source, target_type, horizon_days);

CREATE TABLE IF NOT EXISTS outcomes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_id    BIGINT NOT NULL UNIQUE REFERENCES predictions(id),
    hit              INTEGER NOT NULL,
    realized_return  DOUBLE PRECISION,
    realized_price   DOUBLE PRECISION,
    ref_price        DOUBLE PRECISION,
    signed_error     DOUBLE PRECISION,
    brier            DOUBLE PRECISION,
    detail           TEXT,
    scored_at        TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_outcome_pred ON outcomes(prediction_id);

CREATE TABLE IF NOT EXISTS weight_versions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TEXT NOT NULL,
    source      TEXT NOT NULL,
    weights     TEXT NOT NULL,
    active      INTEGER NOT NULL DEFAULT 0,
    status      TEXT NOT NULL DEFAULT 'proposed',
    rationale   TEXT
);
CREATE INDEX IF NOT EXISTS idx_wv_source_active ON weight_versions(source, active);
CREATE INDEX IF NOT EXISTS idx_wv_source_status ON weight_versions(source, status);

-- ─── Alert Telegram (AlertDB) ───────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS alert_state (
    alert_type        TEXT PRIMARY KEY,
    last_sent_at      TEXT NOT NULL,
    last_payload_hash TEXT NOT NULL
);

-- ─── Prezzi (PriceFetcher) ──────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS prices (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker       TEXT NOT NULL,
    date         TEXT NOT NULL,
    open         DOUBLE PRECISION,
    high         DOUBLE PRECISION,
    low          DOUBLE PRECISION,
    close        DOUBLE PRECISION,
    volume       DOUBLE PRECISION,
    daily_return DOUBLE PRECISION,
    created_at   TEXT,
    UNIQUE (ticker, date)
);
CREATE INDEX IF NOT EXISTS idx_prices_ticker_date ON prices(ticker, date);

-- ─── GEX (GexDB) ────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS gex_snapshots (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date             TEXT NOT NULL,
    asset            TEXT NOT NULL DEFAULT 'BTC',
    timestamp        TEXT NOT NULL,
    spot_price       DOUBLE PRECISION NOT NULL,
    total_net_gex    DOUBLE PRECISION NOT NULL,
    gamma_flip_price DOUBLE PRECISION,
    put_wall         DOUBLE PRECISION,
    call_wall        DOUBLE PRECISION,
    max_pain         DOUBLE PRECISION,
    regime           TEXT,
    total_call_oi    DOUBLE PRECISION,
    total_put_oi     DOUBLE PRECISION,
    put_call_ratio   DOUBLE PRECISION,
    n_instruments    INTEGER,
    created_at       TEXT NOT NULL,
    UNIQUE (date, asset)
);
CREATE INDEX IF NOT EXISTS idx_gex_date ON gex_snapshots(date);

-- ─── Note strutturate EDGAR (StructuredNotesDB) ─────────────────────────────

CREATE TABLE IF NOT EXISTS notes (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filing_url           TEXT NOT NULL UNIQUE,
    issuer               TEXT,
    issue_date           TEXT,
    maturity_date        TEXT,
    notional_usd         DOUBLE PRECISION,
    product_type         TEXT,
    underlying           TEXT DEFAULT 'IBIT',
    initial_level        DOUBLE PRECISION,
    autocall_trigger_pct DOUBLE PRECISION,
    knockin_barrier_pct  DOUBLE PRECISION,
    buffer_pct           DOUBLE PRECISION,
    participation_rate   DOUBLE PRECISION,
    coupon_rate          DOUBLE PRECISION,
    is_preliminary       INTEGER DEFAULT 0,
    observation_dates    TEXT,
    raw_text             TEXT,
    created_at           TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS barrier_levels (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note_id          BIGINT NOT NULL REFERENCES notes(id),
    barrier_type     TEXT NOT NULL,
    level_pct        DOUBLE PRECISION NOT NULL,
    level_price_ibit DOUBLE PRECISION,
    level_price_btc  DOUBLE PRECISION,
    observation_date TEXT,
    status           TEXT DEFAULT 'active',
    created_at       TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS barrier_snapshots (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barrier_id       BIGINT NOT NULL,
    level_price_btc  DOUBLE PRECISION,
    level_price_ibit DOUBLE PRECISION,
    status           TEXT DEFAULT 'active',
    notional_usd     DOUBLE PRECISION,
    issuer           TEXT,
    barrier_type     TEXT,
    snapshot_date    TEXT NOT NULL
        DEFAULT to_char((now() AT TIME ZONE 'UTC'), 'YYYY-MM-DD'),
    created_at       TEXT NOT NULL
        DEFAULT to_char((now() AT TIME ZONE 'UTC'), 'YYYY-MM-DD HH24:MI:SS'),
    UNIQUE (barrier_id, snapshot_date)
);
CREATE INDEX IF NOT EXISTS idx_barrier_snapshots_date ON barrier_snapshots(snapshot_date);
CREATE INDEX IF NOT EXISTS idx_barrier_snapshots_barrier ON barrier_snapshots(barrier_id);

CREATE TABLE IF NOT EXISTS refresh_runs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_at        TEXT NOT NULL,
    filings_seen  INTEGER NOT NULL DEFAULT 0,
    notes_written INTEGER NOT NULL DEFAULT 0,
    ok            INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS idx_refresh_runs_at ON refresh_runs(run_at);

CREATE TABLE IF NOT EXISTS macro_snapshots (
    snapshot_date   TEXT NOT NULL,
    asset           TEXT NOT NULL DEFAULT 'BTC',
    captured_at     TEXT NOT NULL,
    funding_ann_pct DOUBLE PRECISION,
    oi_usd          DOUBLE PRECISION,
    n_contracts     INTEGER,
    PRIMARY KEY (snapshot_date, asset)
);

CREATE INDEX IF NOT EXISTS idx_notes_issuer     ON notes(issuer);
CREATE INDEX IF NOT EXISTS idx_notes_product    ON notes(product_type);
CREATE INDEX IF NOT EXISTS idx_notes_issue_date ON notes(issue_date);
CREATE INDEX IF NOT EXISTS idx_barriers_note    ON barrier_levels(note_id);
CREATE INDEX IF NOT EXISTS idx_barriers_type    ON barrier_levels(barrier_type);
CREATE INDEX IF NOT EXISTS idx_barriers_status  ON barrier_levels(status);
